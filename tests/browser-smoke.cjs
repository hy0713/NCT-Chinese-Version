const fs=require('fs');
const {chromium}=require('./runtime.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.NCT_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();const errors=[],external=[],failed=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400) failed.push([r.status(),r.url()]);});
 await context.route('**/*',route=>{let u=new URL(route.request().url());if(!['localhost','127.0.0.1'].includes(u.hostname)&&!['data:','blob:'].includes(u.protocol)){external.push(u.href);return route.abort();}return route.continue();});
 await page.goto('http://localhost:8000/campaign-trail/index.html');
 await page.waitForTimeout(600);
 console.log('HOME',await page.locator('#game_window').innerText());
 await page.locator('#game_start').first().click();
 await page.waitForTimeout(150);
 console.log('SELECT',await page.locator('#game_window').innerText());
 await page.locator('#election_id').selectOption('3');
 await page.locator('#election_id_button').click();
 await page.locator('#candidate_id').selectOption('16');
 await page.locator('#candidate_id_button').click();
 await page.locator('#running_mate_id').selectOption('30');
 await page.locator('#running_mate_id_button').click();
 console.log('CONFIG',await page.locator('#game_window').innerText());
 await page.locator('#game_type_id').selectOption('1');
 await page.locator('#opponent_selection_id_button').click();
 await page.waitForTimeout(900);
 console.log('QUESTION',await page.locator('#game_window').innerText());
 fs.mkdirSync('.test-artifacts',{recursive:true});await page.screenshot({path:'.test-artifacts/smoke.png',fullPage:true});
 console.log(JSON.stringify({errors,external,failed},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
